import ast as pyast
import io
import os
import sys

HS = os.path.join("aegis", "harness_synth.py")

KW_OLD = '''    "library","struct","enum","event","using","is","virtual","override",
}'''

KW_NEW = '''    "library","struct","enum","event","using","is","virtual","override",
    # Reserved words that appear where an identifier would: `uint256 constant
    # FEE = 1;` and `address payable owner;` both leave a keyword sitting in
    # identifier position. Declaring one as a state variable is a syntax error.
    "constant","immutable","indexed","anonymous","receive","fallback",
    "try","catch","assembly","let","super","selfdestruct","gasleft",
    "returndata","import","pragma","global","transient",
}

# Reserved words must never be emitted as a declaration name, whatever the
# analyzer reports as a storage variable.
_NEVER_DECLARE = {
    "constant","immutable","payable","memory","storage","calldata","public",
    "private","internal","external","view","pure","virtual","override",
    "indexed","anonymous","returns","function","contract","interface",
    "library","struct","enum","event","modifier","constructor","receive",
    "fallback","address","mapping","bool","string","bytes","uint","int",
    "this","msg","block","tx","abi","true","false","new","delete","is",
}'''

HEADER_OLD = '''    return f"""// SPDX-License-Identifier: MIT
{pragma}
/// Auto-generated phase-split harness for {name}.
/// Generated by aegis.harness_synth from exposure site:
///   function {site.function} -> {site.call}  ({site.reason})'''

HEADER_NEW = '''    _site_call = re.sub(r"\\s+", " ", str(getattr(site, "call", "") or "")).strip()
    _site_reason = re.sub(r"\\s+", " ",
                          str(getattr(site, "reason", "") or "")).strip()

    return f"""// SPDX-License-Identifier: MIT
{pragma}
/// Auto-generated phase-split harness for {name}.
/// Generated by aegis.harness_synth from exposure site:
///   function {site.function} -> {_site_call}  ({_site_reason})'''

STATE_OLD = '''    skip = (_GHOST_LEDGER_VARS - _CONTRACT_OWNED_LEDGER) | _RECEIVER_VARS'''

STATE_NEW = '''    skip = ((_GHOST_LEDGER_VARS - _CONTRACT_OWNED_LEDGER) | _RECEIVER_VARS
            | _NEVER_DECLARE)'''

RESOLVE_OLD = '''            if ident not in local_known and ident not in omitted:'''

RESOLVE_NEW = '''            if ident in _NEVER_DECLARE:
                continue
            if ident not in local_known and ident not in omitted:'''


def main():
    if not os.path.exists(HS):
        print("error: run from the aegis_dist root")
        return 1
    text = io.open(HS, encoding="utf-8").read()
    if "_NEVER_DECLARE" in text:
        print("already patched")
        return 0
    io.open(HS + ".bak10", "w", encoding="utf-8").write(text)

    for old, new, label in ((KW_OLD, KW_NEW, "keyword set"),
                            (HEADER_OLD, HEADER_NEW, "header comment"),
                            (STATE_OLD, STATE_NEW, "state block skip"),
                            (RESOLVE_OLD, RESOLVE_NEW, "resolver skip")):
        if old not in text:
            print("error: anchor not found (%s)" % label)
            return 1
        text = text.replace(old, new, 1)

    try:
        pyast.parse(text)
    except SyntaxError as e:
        print("error: would not parse (%s)" % e)
        return 1
    io.open(HS, "w", encoding="utf-8").write(text)
    print("patched %s (backup %s.bak10)" % (HS, HS))
    print("  reserved words excluded from state block and resolver")
    print("  site description flattened to one line in the header comment")
    return 0


if __name__ == "__main__":
    sys.exit(main())
