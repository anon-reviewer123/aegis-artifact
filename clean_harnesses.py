#!/usr/bin/env python3
"""Remove cached harnesses that aegis generated, leaving hand-written ones.

The pipeline now regenerates a stale harness on its own, so this is only
needed once, to clear harnesses written before fingerprinting existed. A
generated harness is recognised by the synthesizer's own banner; a file
without it was written by hand and is never touched.

  python3 clean_harnesses.py --dry-run contracts twins ro_twins
  python3 clean_harnesses.py contracts twins ro_twins loop_twins loop_twins_v2 stress_twins
"""
import argparse
import os

MARKER = "Generated by aegis.harness_synth"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("roots", nargs="*", default=["."],
                    help="directories to search (recursively)")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    generated, handwritten, unreadable = [], [], []
    for root in args.roots:
        for dirpath, _dirs, files in os.walk(root):
            if ".cache" in dirpath or "__pycache__" in dirpath:
                continue
            for f in files:
                if not f.endswith(".harness.sol"):
                    continue
                path = os.path.join(dirpath, f)
                try:
                    text = open(path, errors="replace").read()
                except OSError:
                    unreadable.append(path)
                    continue
                (generated if MARKER in text else handwritten).append(path)

    for p in handwritten:
        print(f"keep    {p}   (hand-written)")
    for p in unreadable:
        print(f"skip    {p}   (unreadable)")
    for p in generated:
        print(f"{'would remove' if args.dry_run else 'removed'}  {p}")
        if not args.dry_run:
            os.remove(p)

    print(f"\ngenerated: {len(generated)}   hand-written kept: {len(handwritten)}")
    if args.dry_run:
        print("dry run: nothing was deleted")


if __name__ == "__main__":
    main()
