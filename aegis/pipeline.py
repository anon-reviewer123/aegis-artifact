@dataclass
class AegisResult:
    status: str        # VERIFIED | BUG_FOUND | UNKNOWN | UNAVAILABLE
    plan: MCVP | None
    candidates_tried: int
    repair_rounds: int
    total_repairs: int
    backend_used: str = "none"
    obligations_report: list = field(default_factory=list)
    # --- A/G core artifact + RQ metrics (for the paper) ---
    ag_decomposition: dict | None = None   # the explicit A/G triple, rendered
    metrics: dict = field(default_factory=dict)  # RQ instrumentation
    log: list[str] = field(default_factory=list)



def _run_loop_verification(facts, backend, say, smt_timeout_ms, sol_path=None,
                           ablate="none"):
    """Build and check the inductive step obligation for each loop-call site.

    The obligation is built around the contract's own extracted loop body, so
    the verdict comes from the solver reasoning about the contract's statements.
    Each site is also checked with a canary obligation whose assertion is
    assert(false): if the canary is not refuted the harness body is unreachable
    and the real verdict would be vacuous, so the site is reported UNKNOWN
    rather than counted.

    Returns (status, reports) with status VERIFIED / BUG_FOUND / UNKNOWN.
    """
    try:
        from loop_step_build import build_loop_step
    except Exception as _e:
        say(f"[loop] step builder unavailable ({_e}); "
            f"place loop_step_build.py on sys.path")
        return "UNKNOWN", []
    if sol_path is None:
        say("[loop] contract source path unavailable; cannot extract loop body")
        return "UNKNOWN", []
    contract_src = open(sol_path).read()

    reports = []
    any_bug = False
    any_checked = False
    for site in facts.loop_sites:
        ob = build_loop_step(contract_src, facts, site, ablate=ablate)
        if ob is None:
            say(f"[loop] {site.function}: unsupported loop shape (skipped)")
            continue
        say(f"[loop] {site.function}: {ob.kind} step obligation")

        if ablate == "canary":
            say(f"      {ob.name}_canary: SKIPPED (ablation)")
            canary = None
        else:
            canary = backend.check_obligation(ob.name + "_canary", "loop",
                                              ob.canary_source, smt_timeout_ms,
                                              ext_calls="trusted")
        _fired, _why = ((True, "") if canary is None
                        else _canary_diagnosis(canary))
        if canary is not None and not _fired:
            _d = getattr(canary, "detail", "") or ""
            say(f"      {ob.name}: CANARY DID NOT FIRE "
                f"(status {getattr(canary, 'status', 'unknown')}); {_why} "
                f"-- reporting UNKNOWN"
                + (f" :: {_d}" if _d else ""))
            reports.append(canary)
            continue
        if canary is not None:
            reports.append(canary)
            say(f"      {ob.name}_canary: fired (harness body reachable)")

        res = backend.check_obligation(ob.name, "loop", ob.harness_source,
                                       smt_timeout_ms, ext_calls="trusted")
        reports.append(res)
        any_checked = True
        st = getattr(res, "status", "unknown")
        say(f"      {ob.name} [{ob.kind}]: {st.upper()}"
            + (f" :: {res.detail}" if getattr(res, 'detail', '') else ""))
        if st == "failed":
            any_bug = True

    if not any_checked:
        return "UNKNOWN", reports
    if any_bug:
        return "BUG_FOUND", reports
    return "VERIFIED", reports


_FP_PREFIX = "/// aegis-harness-fingerprint: "
# Banner the synthesizer has always written. It is what separates a harness
# generated before fingerprinting existed from one a person wrote: the first
# has the banner and no fingerprint, the second has neither.
_GEN_MARKER = "Generated by aegis.harness_synth"


def _readonly_all_sites(facts, contract_src, primary_site, primary_harness,
                        backend, say, smt_timeout_ms, ablate, target_property):
    """Decompose the read-only arm per exposure site.

    Obligations are indexed by site, so a function with two callback-capable
    calls yields two site-local decompositions rather than one. Combining them
    follows the rule that a whole-contract verdict has to hold at every site:
    any refutation stands on its own, a proof needs every windowed site to
    verify, and a single undecided site leaves the contract undecided.
    """
    from . import harness_synth

    windowed = [s for s in facts.exposure_sites
                if s.write_before_call and s.write_after_call]
    if not windowed:
        windowed = [primary_site]

    if len(windowed) > 1:
        say(f"[readonly] {len(windowed)} exposure site(s) with a window; "
            f"decomposing each separately")

    statuses, reports = [], []
    for s in windowed:
        if facts.site_key(s) == facts.site_key(primary_site):
            hc = primary_harness
        else:
            try:
                hc = harness_synth.synthesize_harness(
                    contract_src, facts, s, stable_invariant=target_property)
            except Exception as exc:
                say(f"[readonly] site {s.function}{s.call}#{s.index}: "
                    f"harness construction failed ({exc}); site undecided")
                statuses.append("UNKNOWN")
                continue
        if len(windowed) > 1:
            say(f"[readonly] --- site {s.function}{s.call}#{s.index}")
        st, rep = _run_readonly_verification(
            facts, s, facts.contract, hc, backend, say, smt_timeout_ms,
            ablate=ablate)
        gate = coverage.nesting_gate(facts, s)
        if st == "VERIFIED" and not gate.ok:
            say(f"[gate:nesting] {gate.reason}")
            st = "UNKNOWN"
        statuses.append(st)
        reports.extend(rep)

    decided = [st for st in statuses if st != "NONE"]
    if not decided:
        return "NONE", reports
    if "BUG_FOUND" in decided:
        return "BUG_FOUND", reports
    if all(st == "VERIFIED" for st in decided) and len(decided) == len(statuses):
        return "VERIFIED", reports
    return "UNKNOWN", reports


def _canary_diagnosis(result):
    """Interpret a canary probe. Returns (fired, why).

    The canary replaces the conclusion with assert(false), so a refutation
    means the assertion point is reachable and the real verdict carries
    information. Three non-firing outcomes have to be told apart, because they
    mean different things about the obligation:

      verified  the assertion point is genuinely unreachable, so the real
                obligation would verify for the wrong reason -- a vacuous proof
      unknown   the solver could not decide reachability either way, so
                nothing is known about vacuity
      compile   the harness never reached the solver at all

    Reporting an undecided canary as "unreachable" claims a vacuity result the
    solver never produced. The verdict is UNKNOWN in all three cases, but only
    the first is evidence of vacuity.
    """
    status = getattr(result, "status", "unknown")
    detail = getattr(result, "detail", "") or ""
    if status == "failed":
        return True, ""
    if "compile error" in detail:
        return False, "harness did not compile"
    if status == "verified":
        return False, "harness body unreachable, so a verdict would be vacuous"
    return False, "solver could not decide reachability"


def _harness_fingerprint(contract_src: str, target_property: str = "") -> str:
    """Identity of a synthesized harness: the contract it was built from, the
    target it was built for, and the synthesizer that built it.

    The target is part of it because the harness depends on it: a sum ghost is
    built for each mapping the target names. Without it, a harness cached
    under one target was reused under another and lacked the ghosts the new
    target reads."""
    import hashlib
    from . import harness_synth
    h = hashlib.sha256()
    h.update(contract_src.encode("utf-8", "replace"))
    h.update(b"\0" + (target_property or "").encode("utf-8", "replace"))
    try:
        with open(harness_synth.__file__, "rb") as fh:
            h.update(fh.read())
    except Exception:
        pass
    return h.hexdigest()[:16]


def _load_or_synthesize_harness(hc_path, sol_path, contract_src, facts, site,
                                target_property, fresh, say):
    """Return (harness_source, one-line reason).

    A synthesized harness is written to disk beside the contract so repeated
    runs do not rebuild it. That cache is keyed by a fingerprint over the
    contract source and the synthesizer, because a harness generated by an
    older synthesizer is silently reused otherwise: a fix to harness
    construction then has no effect on any contract that has been run before,
    and the obligations keep failing for a reason the code no longer contains.

    A harness with neither a fingerprint nor the synthesizer's banner was
    written by hand. It is used as it stands and never overwritten. A harness
    carrying the banner but no fingerprint was generated before fingerprinting
    existed, so it is stale by definition and rebuilt.
    """
    from . import harness_synth
    fp = _harness_fingerprint(contract_src, target_property)
    if os.path.exists(hc_path):
        existing = open(hc_path).read()
        if _FP_PREFIX not in existing and _GEN_MARKER not in existing:
            return existing, (f"using hand-written harness "
                              f"{os.path.basename(hc_path)} (no fingerprint; "
                              f"not regenerated)")
        stamped = ""
        for line in existing.splitlines():
            if line.startswith(_FP_PREFIX):
                stamped = line[len(_FP_PREFIX):].strip()
                break
        if stamped == fp and not fresh:
            return existing, (f"reusing synthesized harness "
                              f"{os.path.basename(hc_path)} (fingerprint "
                              f"matches)")
        if not stamped:
            why = "written before harness fingerprinting"
        elif fresh:
            why = "--fresh-harness requested"
        else:
            why = "contract or synthesizer changed since it was written"
        say(f"[harness] cached {os.path.basename(hc_path)} is stale ({why}); "
            f"regenerating")

    hc_src = harness_synth.synthesize_harness(contract_src, facts, site,
                                              stable_invariant=target_property)
    hc_src = _stamp(hc_src, fp)
    with open(hc_path, "w") as fh:
        fh.write(hc_src)
    return hc_src, (f"wrote synthesized harness to "
                    f"{os.path.basename(hc_path)} ({len(hc_src)} chars)")


def _stamp(src: str, fp: str) -> str:
    """Put the fingerprint after the pragma so the file still compiles."""
    lines = src.splitlines()
    for i, line in enumerate(lines):
        if line.strip().startswith("pragma "):
            lines.insert(i + 1, _FP_PREFIX + fp)
            return "\n".join(lines) + "\n"
    return _FP_PREFIX + fp + "\n" + src


def run_aegis(sol_path: str, target_property: str, *args,
              trace_dir: str | None = None, **kwargs) -> "AegisResult":
    """Run the pipeline; with trace_dir, keep everything it produces.

    The trace wraps the whole run, so it is written however the run ends --
    a verdict, a gate, a rejected harness. See aegis/trace.py for the layout.
    """
    from . import trace
    if not trace_dir:
        return _run_aegis_inner(sol_path, target_property, *args, **kwargs)
    trace.start(trace_dir)
    old_err = sys.stderr
    tee = trace.Tee(old_err, os.path.join(trace_dir, "stderr.txt"))
    sys.stderr = tee
    res = None
    try:
        res = _run_aegis_inner(sol_path, target_property, *args, **kwargs)
        return res
    finally:
        sys.stderr = old_err
        tee.close()
        if res is not None:
            trace.write("log.txt", "\n".join(res.log or []))
            _r = {"status": res.status,
                  "candidates_tried": res.candidates_tried,
                  "repair_rounds": res.repair_rounds,
                  "obligations": res.obligations_report,
                  "exposure_invariant": (res.plan.exposure_invariant.formula
                                         if res.plan else None)}
            trace.write_json("result.json", _r)
            trace.summary(_r, res.log or [])
        trace.stop()


def _trivial_target(formula: str) -> bool:
    """True when the target holds in every state: an equality or non-strict
    comparison whose two sides are the same expression, or a constant."""
    import re
    from .validator import degenerate_invariant
    f = re.sub(r"\s+", "", formula or "")
    if f in ("", "true", "(true)"):
        return True
    m = re.fullmatch(r"\(?(.+?)(==|<=|>=)(.+?)\)?", f)
    if m and m.group(1) == m.group(3):
        return True
    return degenerate_invariant(formula, ghosts=())


def _run_aegis_inner(sol_path: str, target_property: str,
              llm_backend: str = "stub", k: int = 4,
              max_repair_rounds: int = 8, smt_timeout_ms: int = 0,
              verbose: bool = True,
              ablate: str = "none", repair: str = "cegar-reuse",
              fresh_harness: bool = False,
              sites: str = "primary",
              slice_mode: str = "off") -> AegisResult:
    config = ExperimentConfig(ablate=ablate, repair=repair, sites=sites,
                              slice=slice_mode)
    compiler.SLICE = (config.slice == "on")
    counters = RQ4Counters()
    log: list[str] = []

    def say(s: str):
        log.append(s)
        if verbose:
            print(s)

    say(f"== Aegis on {os.path.basename(sol_path)} ==")
    say(f"target property: {target_property}")
    if _trivial_target(target_property):
        # A target true in every state proves nothing; a proof of it would be
        # a VERIFIED about no property (SummoningOfTheWicked, `demons == demons`).
        say("[!] the target is true in every state; there is no property to verify")
        return AegisResult("UNKNOWN", None, 0, 0, 0, "none",
                           [{"obligation": "target", "module": "target",
                             "status": "unknown",
                             "detail": "target is a tautology"}], log=log)

    # ETH-balance modeling: address(this).balance is not trackable storage.
    # Rewrite it to a ghost var _ethBal (credited by msg.value, debited by
    # transfer/send) so the classic-reentrancy balance property is verifiable.
    _eth_src, target_property, _eth_changed = (None, target_property, False)
    try:
        _orig = open(sol_path).read()
        _new, target_property, _eth_changed = eth_model.transform(_orig, target_property)
        if _eth_changed:
            import tempfile, os as _os
            _tmp = sol_path.replace(".sol", ".ethmodel.sol")
            open(_tmp, "w").write(_new)
            sol_path = _tmp
            say(f"[eth-model] address(this).balance -> _ethBal; "
                f"property now: {target_property}")
            from . import trace as _tr
            _tr.write("contract.sol", _new)
    except Exception as _e:
        say(f"[eth-model] skipped: {_e}")

    # Backend banner -- never let a simulated result masquerade as real.
    if backend.solc_healthy():
        say("[backend] REAL SMTChecker (solc on PATH) -- results are sound")
        backend_used = "smtchecker"
    else:
        say("[backend] *** NO REAL VERIFIER: solc not on PATH ***")
        say("[backend] *** results will be UNAVAILABLE, never VERIFIED ***")
        say("[backend] install: pip install solc-select && "
            "solc-select install 0.8.26 && solc-select use 0.8.26")
        backend_used = "none"

    facts = static_analysis.analyze(sol_path)
    say(f"[1] static analysis ({static_analysis.LAST_ANALYZER}): "
        f"storage={facts.storage_vars}")
    if static_analysis.LAST_ANALYZER != "ast":
        say("[1] NOTE: regex analyzer used (no working solc AST); "
            "soundness claim requires the AST analyzer")
    loop_status, loop_reports = ("NONE", [])
    if getattr(facts, "loop_sites", None):
        say(f"[loop] {len(facts.loop_sites)} loop-call site(s) detected")
        loop_status, loop_reports = _run_loop_verification(
            facts, backend, say, smt_timeout_ms, sol_path=sol_path,
            ablate=config.ablate)
        # The loop step is proved under the same depth-one adversary, so the
        # nesting gate applies to it too. The coverage gate does not: the loop
        # arm already discharges every loop site it recognised.
        if loop_status == "VERIFIED":
            _lsite = next((s for s in facts.exposure_sites
                           if any(s.function == l.function
                                  for l in facts.loop_sites)), None)
            if _lsite is not None:
                _g = coverage.nesting_gate(facts, _lsite)
                if not _g.ok:
                    say(f"[gate:nesting] {_g.reason}")
                    loop_status = "UNKNOWN"
        say(f"[loop] loop verification: {loop_status}")
        # Loop verification is authoritative for a loop-callback contract: if it
        # produced a definitive verdict, return it (do not fall through to the
        # exposure-invariant path, which does not model the loop).
        if loop_status in ("VERIFIED", "BUG_FOUND"):
            return AegisResult(loop_status, None, 0, 0, 0,
                               backend_used, _report(loop_reports), log=log)

    if not facts.exposure_sites:
        say("no callback-exposed sites found; nothing to verify")
        return AegisResult("UNKNOWN", None, 0, 0, 0, backend_used,
                           _report(loop_reports), log=log)

    site = facts.exposure_sites[0]
    conservative = facts.conservative_closure(site)
    say(f"[2] exposure site: {site.function} -> {site.call} ({site.reason})")
    say(f"    conservative closure: {sorted(conservative)}")
    if facts.privileged:
        _acc = sorted(n for n, g in facts.privileged.items() if g[0] == "access")
        _eoa = sorted(n for n, g in facts.privileged.items() if g[0] == "eoa")
        if _acc:
            say(f"[access] outside the closure under the trusted-roles "
                f"assumption: {_acc}")
        if _eoa:
            say(f"[access] outside the closure as EOA-only (tx.origin gate; "
                f"weaker since EIP-7702): {_eoa}")
        for _n in sorted(facts.privileged):
            say(f"    {_n}: {facts.privileged[_n][1]}")

    _unbounded = sorted(f for f in conservative
                        if facts.reaches_unbounded_write(f))
    if _unbounded:
        _why = (f"closure member(s) {_unbounded} may write storage no analysis "
                f"can bound (delegatecall or storage-writing assembly); a "
                f"callback may call them, so no proof is possible")
        say(f"[!] {_why}")
        return AegisResult("UNKNOWN", None, 0, 0, 0, backend_used,
                           [{"obligation": "closure_bounded", "module": "closure",
                             "status": "unknown", "detail": _why}],
                           log=log)

    hc_path = sol_path.replace(".sol", ".harness.sol")
    contract_src = open(sol_path).read()
    hc_src, reason = _load_or_synthesize_harness(hc_path, sol_path, contract_src,
                                                 facts, site, target_property,
                                                 fresh_harness, say)
    from . import trace as _tr
    _tr.write("harness.sol", hc_src)
    say(f"[harness] {reason}")

    # Enforce the harness interface contract. A non-conforming harness silently
    # produces broken or vacuous obligations -- refuse to run rather than emit
    # a meaningless VERIFIED.
    from . import harness_check
    report = harness_check.check_harness(hc_src, list(conservative),
                                         exposed_function=site.function)
    if not report.conforming:
        say(f"[!] {report.diagnostic}")
        # log is passed by name: positionally it lands in ag_decomposition,
        # which is the field that follows obligations_report, and the run log
        # then reads as empty -- the one path where the reason matters most.
        return AegisResult("HARNESS_NONCONFORMING", None, 0, 0, 0, backend_used,
                           [{"obligation": "harness_interface", "module": "harness",
                             "status": "failed", "detail": report.diagnostic}],
                           log=log)
    say(f"[harness] conforms to interface "
        f"(found {len(report.found_functions)} functions, "
        f"{len(report.found_state_vars)} public state vars)")

    ro_status, ro_reports = _readonly_all_sites(
        facts, contract_src, site, hc_src, backend, say, smt_timeout_ms,
        config.ablate, target_property)
    # The coverage gate is not applied here: the read-only arm has just
    # decomposed every windowed site itself, so there is nothing left
    # uncovered. The nesting gate was applied per site inside.
    if ro_status in ("VERIFIED", "BUG_FOUND"):
        say(f"[readonly] read-only verification: {ro_status}")
        return AegisResult(ro_status, None, 0, 0, 0, backend_used,
                           _report(ro_reports), log=log)

    def _general_for_site(the_site, the_harness, cover_all):
        """Run the MCVP arm at one exposure site and return its result."""
        if config.ablate != "none":
            say(f"[ABLATION] mode={config.ablate}")
        if config.repair != "cegar-reuse":
            say(f"[REPAIR] strategy={config.repair}")
        # Candidates are produced lazily. When the pre-phase writes none of
        # the target's variables the plan is determined by the site, so it is
        # tried first and the proposer is not called at all unless it fails --
        # every model call costs money, and that one buys nothing.
        _cons = sorted(facts.conservative_closure(the_site))

        def _normalise(p):
            """Closure and protocol set to the conservative closure, which is
            exactly what soundness requires. A proposer's closure can only
            differ by being unsound (a missing reachable callback, which the
            validator rejected) or by being padded: on ReservaX it added
            fourteen owner-only setters the access filter had excluded, each
            becoming an obligation re-solved every round."""
            if config.ablate != "none":
                return p
            if sorted(p.closure.functions) != _cons:
                _dropped = [f for f in p.closure.functions if f not in _cons]
                _added = [f for f in _cons if f not in p.closure.functions]
                p.closure.functions = list(_cons)
                p.protocol.allowed_callbacks = list(_cons)
                p.protocol.nesting_bound = {f: 1 for f in _cons}
                if _dropped or _added:
                    say(f"[3] closure set to the conservative closure "
                        f"({len(_cons)} member(s))"
                        + (f"; dropped {_dropped[:6]}" if _dropped else "")
                        + (f"; added {_added[:6]}" if _added else ""))
            return p

        _det = []
        if config.ablate == "none":
            _sw = synth.stable_window_plan(facts, the_site, target_property)
            if _sw is not None:
                _det.append((_sw, "the pre-phase writes none of the target's "
                                  "variables, so the target itself holds at "
                                  "the call"))
            _ne = synth.net_effect_plan(facts, the_site, target_property,
                                        harness_src=hc_src)
            if _ne is not None and not any(
                    p.exposure_invariant.formula == _ne.exposure_invariant.formula
                    for p, _ in _det):
                _entry = (_ne, "computed from what the pre-phase moves: "
                               f"{_ne.exposure_invariant.formula}")
                # When the post-phase settles a value the pre-phase read, the
                # plan carrying that fact is the only one that can discharge
                # OBL_post: without it the obligation is refuted from states
                # where the captured figure and the state it came from differ.
                # So it goes first, rather than after a weaker plan spends the
                # rounds on an obligation nothing can repair.
                if synth._captures(hc_src or ""):
                    _det.insert(0, _entry)
                else:
                    _det.append(_entry)

        def _candidates():
            for _p, _why in _det:
                say(f"[3] deterministic candidate -- {_why}")
                yield _normalise(_p)
            say(f"[3] sampling {k} candidate MCVPs ({llm_backend})")
            for _p in synth.sample_plans(facts, the_site, target_property,
                                         backend=llm_backend, k=k,
                                         ablate=config.ablate):
                yield _normalise(_p)

        cands = _candidates()
        local_best = None
        _tried = 0
        for ci, plan in enumerate(cands):
            _tried = ci + 1
            say(f"-- candidate {ci} --")
            from . import trace as _tr
            _tr.context["candidate"] = ci
            _tr.context["round"] = None
            r = _fixpoint(plan, facts, the_site, target_property, conservative,
                          the_harness, max_repair_rounds, llm_backend,
                          smt_timeout_ms, backend_used, say, config, counters,
                          cover_all_sites=cover_all)
            r.candidates_tried = ci + 1
            r.backend_used = backend_used
            if r.status in ("VERIFIED", "BUG_FOUND"):
                return r
            local_best = r
        say("no candidate verified -> "
            + ("UNAVAILABLE (no backend)" if backend_used == "none"
               else "UNKNOWN"))
        if local_best:
            local_best.candidates_tried = _tried
            return local_best
        return AegisResult("UNKNOWN", None, _tried, 0, 0, backend_used, [])

    def _finish(r):
        r.log = log
        r.metrics["smtchecker_calls"] = counters.smtchecker_calls
        r.metrics["reuse_hits"] = counters.reuse_hits
        r.metrics["wall_clock_sec"] = counters.elapsed()
        return r

    windowed = [s for s in facts.exposure_sites
                if s.write_before_call and s.write_after_call]
    decompose_all = (config.sites == "all" and len(windowed) > 1)

    if not decompose_all:
        return _finish(_general_for_site(site, hc_src, False))

    # Per-site decomposition. Obligations are indexed by site, and a
    # whole-contract verdict has to hold at every one of them: a refutation
    # stands on its own, a proof needs every windowed site to verify, and one
    # undecided site leaves the contract undecided.
    say(f"[3] decomposing {len(windowed)} exposure site(s) separately "
        f"(--sites all)")
    from . import harness_synth
    results, worst = [], None
    for s_i in windowed:
        say(f"[3] --- site {s_i.function}{s_i.call}#{s_i.index}")
        if facts.site_key(s_i) == facts.site_key(site):
            h = hc_src
        else:
            try:
                h = harness_synth.synthesize_harness(
                    contract_src, facts, s_i, stable_invariant=target_property)
            except Exception as exc:
                say(f"[3] harness construction failed at this site ({exc}); "
                    f"site undecided")
                results.append("UNKNOWN")
                continue
        r = _general_for_site(s_i, h, True)
        results.append(r.status)
        if r.status == "BUG_FOUND":
            say(f"[3] refuted at site {s_i.function}{s_i.call}#{s_i.index}")
            return _finish(r)
        worst = r if worst is None or r.status != "VERIFIED" else worst

    final = worst or AegisResult("UNKNOWN", None, 0, 0, 0, backend_used, [])
    if "UNAVAILABLE" in results:
        # No backend is a property of the run, not of the decomposition, and
        # must not be reported as an undecided site.
        say("[3] no backend available -> UNAVAILABLE")
        final.status = "UNAVAILABLE"
    elif all(st == "VERIFIED" for st in results):
        say(f"[3] every site verified ({len(results)}) -> VERIFIED")
        final.status = "VERIFIED"
    else:
        undecided = [st for st in results if st != "VERIFIED"]
        say(f"[3] {len(undecided)} of {len(results)} site(s) not verified "
            f"-> UNKNOWN")
        final.status = "UNKNOWN"
    return _finish(final)


def _run_readonly_verification(facts, site, contract_name, hc_src, backend,
                               say, smt_timeout_ms, ablate="none"):
    """Check the differential view-safety obligations on their own.

    This runs before exposure-invariant synthesis because the view check needs
    no invariant: it compares what a public view returns inside the exposed
    window against what it returns after the window settles, and divergence is a
    concrete read-only reentrancy witness. Gating it behind invariant synthesis
    would make a contract with no synthesizable accounting invariant report
    UNKNOWN for a reason unrelated to read-only safety.

    Each view is probed with a canary first. If the canary is not refuted the
    harness body is unreachable, so that view is reported UNKNOWN and excluded
    rather than counted.

    Returns (status, reports) with status VERIFIED / BUG_FOUND / UNKNOWN / NONE.
    """
    try:
        obls = compiler.compile_view_obligations(facts, site, contract_name,
                                                 hc_src, ablate=ablate)
        canaries = compiler.compile_view_obligations(facts, site, contract_name,
                                                     hc_src, canary=True,
                                                     ablate=ablate)
    except Exception as _e:
        say(f"[readonly] view obligations unavailable ({_e})")
        return "NONE", []
    from . import guards
    _g = guards.explain(facts, site)
    if _g:
        say(f"[readonly] {_g}")

    for v in getattr(compiler, "VIEW_ADMISSIBILITY", []):
        if not v.admitted:
            say(f"[readonly] {v.view}: rule inapplicable -- {v.reason}; "
                f"falling through to the general arm")

    if not obls:
        return "NONE", []

    say(f"[readonly] {len(obls)} public view(s) admitted by the footprint "
        f"premise on the window opened by {site.function}")
    by_name = {c.name.replace("_canary", ""): c for c in canaries}
    reports, any_bug, any_checked = [], False, False
    for ob in obls:
        can = None if ablate == "canary" else by_name.get(ob.name)
        if ablate == "canary":
            say(f"      {ob.name}_canary: SKIPPED (ablation)")
        if can is not None:
            cr = backend.check_obligation(can.name, "readonly",
                                          can.harness_source, smt_timeout_ms)
            _fired, _why = _canary_diagnosis(cr)
            if not _fired:
                _d = getattr(cr, "detail", "") or ""
                say(f"      {ob.name}: CANARY DID NOT FIRE "
                    f"(status {getattr(cr, 'status', 'unknown')}); {_why} "
                    f"-- reporting UNKNOWN for this view"
                    + (f" :: {_d}" if _d else ""))
                reports.append(cr)
                continue
            reports.append(cr)
            say(f"      {can.name}: fired (harness body reachable)")
        res = backend.check_obligation(ob.name, "readonly", ob.harness_source,
                                       smt_timeout_ms)
        reports.append(res)
        any_checked = True
        st = getattr(res, "status", "unknown")
        say(f"      {ob.name}: {st.upper()}")
        if st == "failed":
            any_bug = True

    if not any_checked:
        return "UNKNOWN", reports
    if any_bug:
        return "BUG_FOUND", reports
    return "VERIFIED", reports


def _iexp_is_stable(plan) -> bool:
    inv = plan.exposure_invariant
    return inv.formula.strip() == inv.stable_formula.strip()


def _confirm_candidate(facts, site, target_property, smt_timeout_ms, say):
    """(verdict, why) from reproducing the property on the original contract."""
    from . import confirm
    try:
        src = open(facts.path, errors="ignore").read()
    except Exception as exc:
        return "undecided", f"source unreadable: {exc}"
    return confirm.confirm(src, facts.contract, target_property,
                           set(getattr(facts, "privileged", {}) or {}),
                           site.function, smt_timeout_ms or 120000, say)


def _fixpoint(plan, facts, site, target_property, conservative, hc_src,
              max_repair_rounds, llm_backend, smt_timeout_ms, backend_used, say,
              config=None, counters=None, cover_all_sites=False):
    if config is None:
        config = ExperimentConfig()
    if counters is None:
        counters = RQ4Counters()

    # RQ4: --repair none → single round, no repair
    effective_rounds = 1 if config.repair == "none" else max_repair_rounds

    total_repairs = 0
    dirty = set(depgraph.ALL_MODULES)
    last_results = []

    cache = proof_cache.ProofCache()
    verified_states: list[dict] = []
    known_idents = set(facts.storage_vars) | {g.name for g in plan.ghost_state}

    for rnd in range(1, effective_rounds + 1):
        from . import trace as _tr
        _tr.context["round"] = rnd
        _tr.write_json(f"plans/c{_tr.context['candidate']}_r{rnd}.json", plan)
        # (a) validate: schema + conservative-closure SOUNDNESS gate
        # RQ3: --ablate validator → skip validation entirely
        if config.ablate == "validator":
            failed_val = []
        else:
            failed_val = validator.validate(plan, facts, site,
                                            ablate=config.ablate)
        if failed_val:
            say(f"  [round {rnd}] validation flagged: {failed_val}")
            if config.repair == "none":
                say(f"  [round {rnd}] --repair none: skipping repair")
                return AegisResult("UNKNOWN", plan, 0, rnd, total_repairs,
                                   backend_used, [{"obligation": "validation",
                                    "module": ",".join(failed_val),
                                    "status": "failed",
                                    "detail": f"validation rejected: {failed_val}"}])
            detail = (f"validation rejected modules: {failed_val}. "
                      f"Common causes: closure omits a reachable callback; "
                      f"protocol's allowed_callbacks must equal the closure; "
                      f"exposure invariant must reference every storage var the "
                      f"target property mentions (no vacuous invariants using "
                      f"unconstrained ghosts); exposure invariant must be "
                      f"strictly weaker than the stable invariant.")
            for m in depgraph.repair_order(set(failed_val)):
                plan = synth.repair_module(plan, m, facts, site, target_property,
                                           backend=llm_backend,
                                           failure_detail=detail,
                                           ablate=config.ablate)
                total_repairs += 1
                dirty |= {m} | depgraph.downstream_of({m})
            continue
        say(f"  [round {rnd}] validation passed")

        # refresh known identifiers (ghost set may have changed via repair)
        known_idents = set(facts.storage_vars) | {g.name for g in plan.ghost_state}
        ghost_names = [g.name for g in plan.ghost_state]
        inv_new = plan.exposure_invariant.formula

        # (b) compile per-obligation harnesses
        obligations = compiler.compile_obligations(plan, facts, hc_src,
                                                   ablate=config.ablate)
        if getattr(compiler, "EMISSION_ERRORS", None):
            for _lbl, _err in compiler.EMISSION_ERRORS:
                say(f"  [round {rnd}] *** OBLIGATION EMISSION FAILED: {_lbl}: {_err} ***")
                say(f"  [round {rnd}] *** a missing operative obligation means a "
                    f"VERIFIED verdict on this contract is NOT trustworthy ***")
        say(f"  [round {rnd}] compiled {len(obligations)} obligations: "
            f"{[o.name for o in obligations]}")
        if compiler.SLICE and compiler.SLICE_STATS:
            _b = max(b for b, _ in compiler.SLICE_STATS)
            _a = max(a for _, a in compiler.SLICE_STATS)
            say(f"  [round {rnd}] sliced harness: up to {_b} state variables "
                f"-> at most {_a} per obligation")

        # (b2) Idea 2: PROOF REUSE.
        # RQ4: only --repair cegar-reuse enables proof reuse
        to_check = []
        reused_results = []
        if config.repair == "cegar-reuse":
            for ob in obligations:
                if ob.name.startswith("OBL_cb_"):
                    dec = cache.try_reuse(ob.name, inv_new,
                                          facts.storage_vars, ghost_names)
                    if dec.reused:
                        say(f"      {ob.name} [closure]: REUSED :: {dec.reason}")
                        reused_results.append(backend.ObligationResult(
                            ob.name, ob.module, "verified",
                            f"reused cached proof ({dec.reason})"))
                        counters.reuse_hits += 1
                        continue
                    if dec.witness:
                        say(f"      {ob.name}: reuse declined ({dec.reason}); "
                            f"witness {dec.witness}")
                to_check.append(ob)
        else:
            to_check = list(obligations)

        # (c) REAL backend check (only on the not-reused obligations)
        checked = backend.run(to_check, timeout_ms=smt_timeout_ms)
        counters.smtchecker_calls += len(to_check)
        results = reused_results + checked
        # keep a stable obligation order for reporting
        order = {o.name: i for i, o in enumerate(obligations)}
        results.sort(key=lambda r: order.get(r.name, 1_000))
        last_results = results
        for r in results:
            if r.detail.startswith("reused cached proof"):
                continue  # already printed as REUSED
            tag = r.status.upper()
            extra = f" :: {r.detail}" if r.status != "verified" else ""
            say(f"      {r.name} [{r.module}]: {tag}{extra}")

        # (c2) Idea 2: populate the cache from freshly-verified callback proofs,
        # and (Idea 1) log the verified pre-state for refinement preservation.
        for r in results:
            if r.status == "verified" and r.name.startswith("OBL_cb_"):
                cb = r.name[len("OBL_cb_"):]
                cache.record_verified(r.name, cb, inv_new, rnd)
        # A canonical "stable, settled" safe state: inFlight==0 reduces I_exp to
        # I_stable, so totalAssets==totalShares with all ghosts zero is a state
        # every correct invariant must keep. Record it once.
        if not verified_states and any(r.status == "verified" for r in results):
            safe = {g.name: 0 for g in plan.ghost_state}
            for v in facts.storage_vars:
                safe.setdefault(v, 0)
            verified_states.append(safe)

        # If there is no real backend, stop honestly.
        if any(r.status == "no_backend" for r in results):
            return AegisResult("UNAVAILABLE", plan, 0, rnd, total_repairs,
                               backend_used, _report(results))

        # bug detection: a concrete counterexample on an obligation that
        # represents a REAL exploit. A failed OBL_pre is special: the pre-phase
        # establishes I_exp from I_stable, so it can only fail when the
        # synthesized exposure invariant is wrong (e.g. wrong ghost direction),
        # NOT because the contract is buggy. We therefore route OBL_pre failures
        # to the repair loop (Idea 1 CEGAR refinement flips/strengthens I_exp)
        # instead of declaring BUG_FOUND. OBL_post and OBL_cb_* failures remain
        # genuine bug candidates (e.g. BuggyVault fails OBL_post by not settling
        # the ghost; a malicious callback fails OBL_cb_* by violating I_exp).
        # Deterministic operative obligations: OBL_conservation (flash-loan),
        # OBL_reentry (classic), OBL_readonly (read-only). Unlike OBL_cb_* (whose
        # verdict depends on the LLM-synthesized invariant's strength) these
        # inject the contract's own predicate and reliably split safe/unsafe
        # twins. When one is present and VERIFIED, the contract is safe along
        # that path, so a phase-obligation (OBL_post) counterexample -- which on
        # conservation/observation shapes is a solver-unstable model artifact
        # (it flips between unknown-timeout and failed across runs) -- must not
        # produce a false BUG_FOUND. OBL_pre is already excluded (routes to
        # repair). A genuine exploit still fails the deterministic obligation
        # (gate False) and is reported.
        # A deterministic operative obligation injects the contract's own predicate
        # and reliably splits safe/unsafe twins: OBL_conservation (flash-loan),
        # OBL_reentry (classic), OBL_readonly (planted-invariant), and OBL_view_*
        # (the differential view obligation -- the operative read-only check that
        # actually carves from the contract's own view). OBL_view_* names carry a
        # view-specific suffix, so we match by prefix.
        def _is_det_name(nm):
            return (nm in ("OBL_conservation", "OBL_reentry", "OBL_readonly")
                    or nm.startswith("OBL_view_"))
        _det = [r for r in results if _is_det_name(r.name)]
        _det_verified = bool(_det) and all(r.status == "verified" for r in _det)
        # A deterministic operative obligation that FAILED is an exploit witness
        # regardless of whether a counterexample trace string was extracted (the
        # untrusted-mode violation is the signal; the trace text is incidental
        # and its capture is itself solver-timing-dependent). For other failed
        # obligations we still require a counterexample to avoid acting on a
        # bare timeout misreported as failed.
        for r in results:
            if r.status != "failed":
                continue
            is_det = _is_det_name(r.name)
            if not is_det and not r.counterexample:
                continue
            if r.name == "OBL_pre":
                continue
            # A failed OBL_post used to be discarded here whenever a
            # deterministic obligation verified, on the grounds that it was a
            # phase-model artifact. Those artifacts came from phase bodies that
            # lost statements during extraction and from ledger writes the
            # harness substituted for the contract's own; with both corrected,
            # OBL_post fails only when the post phase genuinely does not restore
            # the stable invariant, which is the defect the obligation exists to
            # catch. Suppressing it reports VERIFIED for a contract whose
            # G_post guarantee was never discharged.
            # A deterministic obligation runs the original contract already, so
            # its failure is a witness. Any other refutation was found against
            # the exposure invariant, which on deployed code is often not what
            # the contract reaches at the call; it is a candidate until the
            # original contract reproduces it (aegis/confirm.py).
            if r.name.endswith("_canary"):
                # a refuted canary is the GOOD case: the state it probes is
                # reachable, which is what makes the proof beside it mean
                # something. It is never a defect in the contract.
                continue
            if not is_det:
                verdict, why = _confirm_candidate(facts, site, target_property,
                                                  smt_timeout_ms, say)
                say(f"  [round {rnd}] candidate via {r.name}: {verdict} -- {why}")
                if verdict == "confirmed":
                    pass
                elif verdict == "not_invariant":
                    say(f"  [round {rnd}] the target is violated without any "
                        f"callback; not a reentrancy finding")
                    return AegisResult("UNKNOWN", plan, 0, rnd, total_repairs,
                                       backend_used, _report(results))
                else:
                    # Not reproduced, or undecided. An undecided confirmation
                    # used to be reported when OBL_pre held, on the grounds
                    # that the exposure invariant holds at every real window
                    # state. But a callback that breaks the exposure invariant
                    # need not break the target, which can be weaker, and its
                    # starting state need not be reachable; X7RLiquidityHub,
                    # labelled safe, was reported that way. A bug is reported
                    # only when the original contract reproduces it.
                    continue
            say(f"  [round {rnd}] BUG_FOUND via {r.name}")
            if r.counterexample:
                say(f"      counterexample: {r.counterexample}")
            return AegisResult("BUG_FOUND", plan, 0, rnd, total_repairs,
                               backend_used, _report(results))

        # (d) localize failures to modules
        loc = localize_mod.localize(plan, results)
        in_prog = loc.in_progress_modules()
        # Nothing to repair when the solver simply did not answer: the plan is
        # not wrong, it is out of reach, and re-running identical obligations
        # spends the budget that the next candidate needs.
        # A canary that fired is the good outcome, not an open obligation;
        # counting it kept BPYC repairing an undecided canary for two rounds.
        _open = [r for r in results if r.status != "verified"
                 and not (r.name.endswith("_canary") and r.status == "failed")]
        if in_prog and _open and all(r.status == "unknown" for r in _open):
            say(f"  [round {rnd}] every open obligation is undecided; the plan "
                f"is not repairable -- moving to the next candidate")
            return AegisResult("UNKNOWN", plan, 0, rnd, total_repairs,
                               backend_used, _report(results))
        say(f"  [round {rnd}] correct={loc.correct_modules()} "
            f"in_progress={sorted(in_prog)}")

        if loc.all_correct():
            # When the caller decomposes every site itself there is nothing
            # left uncovered, so only the nesting gate applies; the coverage
            # gate exists precisely to compensate for a single-site proof.
            if cover_all_sites:
                gated = "VERIFIED"
                _ng = coverage.nesting_gate(facts, site)
                if not _ng.ok:
                    say(f"[gate:nesting] {_ng.reason}")
                    gated = "UNKNOWN"
            else:
                gated = coverage.apply_gates(facts, site, "VERIFIED", say)
            if gated != "VERIFIED":
                return AegisResult(gated, plan, 0, rnd, total_repairs,
                                   backend_used, _report(results))
            say(f"  [round {rnd}] FIXPOINT -> VERIFIED (real solver)")
            from . import assume_guarantee as ag
            decomp = ag.derive(plan)
            say("")
            say(decomp.render())
            metrics = {
                "obligations_total": len(results),
                "obligations_verified": sum(1 for r in results
                                            if r.status == "verified"),
                "repair_rounds": rnd,
                "total_repairs": total_repairs,
                "ag_components": len(decomp.components()),
                "callback_closure_size": len(plan.closure.functions),
                # Idea 2: proof-reuse payoff (RQ on re-verification cost)
                "proof_reuse_hits": cache.stats()["reuse_hits"],
                "proof_reuse_misses": cache.stats()["reuse_misses"],
                "cached_proofs": cache.stats()["cached_proofs"],
            }
            return AegisResult("VERIFIED", plan, 0, rnd, total_repairs,
                               backend_used, _report(results),
                               ag_decomposition={"rendered": decomp.render(),
                                                 "theorem": decomp.composition_theorem()},
                               metrics=metrics)

        # (e) repair in dependency order; propagate dirtiness
        # RQ4: --repair none → effective_rounds=1, loop exits after this round
        if config.repair == "none":
            continue

        module_to_failures: dict[str, list[str]] = {}
        raw_cex_for_module: dict[str, str] = {}
        for r in results:
            if r.status in ("failed", "unknown"):
                module_to_failures.setdefault(r.module, []).append(
                    f"{r.name} ({r.status}): {r.detail}"
                    + (f"; counterexample: {r.counterexample}"
                       if r.counterexample else ""))
                if r.counterexample:
                    raw_cex_for_module[r.module] = r.counterexample

        # RQ4: --repair whole-regen → discard entire MCVP and sample a fresh one
        if config.repair == "whole-regen":
            fresh_plans = synth.sample_plans(facts, site, target_property,
                                             backend=llm_backend, k=1,
                                             ablate=config.ablate)
            if fresh_plans:
                plan = fresh_plans[0]
            total_repairs += 1
            dirty = set(depgraph.ALL_MODULES)
            say(f"  [round {rnd}] whole-regen: replaced entire MCVP")
            continue

        for m in depgraph.repair_order(in_prog):
            # RQ4: --repair raw → pass raw solver text, skip CEGAR projection
            # RQ4: --repair cegar or cegar-reuse → CEGAR refinement
            if m == "exposure_invariant" and config.repair in ("cegar", "cegar-reuse"):
                block, _cm = refinement.refine(
                    raw_cex_for_module.get(m, ""),
                    obligation="exposure_invariant", module=m,
                    known_idents=known_idents,
                    verified_states=verified_states)
                detail = block
                say(f"  [round {rnd}] CEGAR refinement constraint built for "
                    f"exposure_invariant")
            else:
                detail = "\n".join(module_to_failures.get(m, []))

            prev_closure = set(plan.closure.functions)
            plan = synth.repair_module(plan, m, facts, site, target_property,
                                       backend=llm_backend,
                                       failure_detail=detail,
                                       ablate=config.ablate)
            total_repairs += 1
            dirty |= {m} | depgraph.downstream_of({m})

            if m == "closure":
                for gone in prev_closure - set(plan.closure.functions):
                    cache.invalidate_for_callback(gone)

    say(f"  repair budget ({effective_rounds}) exhausted -> UNKNOWN")
    return AegisResult("UNKNOWN", plan, 0, effective_rounds, total_repairs,
                       backend_used, _report(last_results))


def _report(results):
    return [{"obligation": r.name, "module": r.module, "status": r.status,
             "detail": r.detail} for r in results]
