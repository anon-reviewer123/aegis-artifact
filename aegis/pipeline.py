"""
pipeline.py - The Aegis(C, phi) driver: dependency-driven fixpoint repair over
an assume-guarantee MCVP, checked by a REAL backend.

Honesty guarantees:
  * A plan is VERIFIED only if a real solver discharged EVERY obligation.
  * If solc is not installed, status is UNAVAILABLE -- never VERIFIED.
  * A concrete counterexample on an obligation yields BUG_FOUND with the trace.
"""
